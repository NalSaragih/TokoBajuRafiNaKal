    private void addCartBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addCartBtnActionPerformed
        if (currentProduct == null) {
            return;
        }
        boolean added = CartModel.getInstance().addItem(currentProduct, 1);
        if (added) {
            JOptionPane.showMessageDialog(this,
                    "\"" + currentProduct.getProductName() + "\" ditambahkan ke keranjang!");
        } else {
            JOptionPane.showMessageDialog(this,
                    "Stok tidak mencukupi untuk menambah lagi!",
                    "Stok Habis",
                    JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_addCartBtnActionPerformed

